//! Disaggregated Prefill / Decode over the NIXL Fabric
//!
//! # Architecture
//!
//! ```text
//!  ┌───────────────────────┐     NIXL KV transfer      ┌────────────────────────┐
//!  │   Prefill Pool        │ ─────────────────────────► │   Decode Pool          │
//!  │  (compute-bound)      │   cold KV blocks migrate   │  (memory-bound)        │
//!  │  - runs prompt attn   │                            │  - runs auto-regressive│
//!  │  - fills KV cache     │                            │    decode steps         │
//!  └───────────────────────┘                            └────────────────────────┘
//!            ▲                                                      │
//!            │             DisaggPool                               │
//!            └──────────────(orchestrator)──────────────────────────┘
//! ```
//!
//! # Key Types
//!
//! * [`NodeRole`] — marks a NIXL agent as `Prefill` or `Decode`.
//! * [`DisaggPool`] — holds two [`CacheTransferAgent`] pools (prefill / decode),
//!   routes [`PrefillTask`]s through NIXL, and hands [`DecodeTask`]s to decode nodes.
//! * [`DisaggStats`] — aggregated telemetry across both pools.
//! * [`build_disagg_pool`] — convenience constructor that wires everything.

use std::sync::Arc;

use crate::nixl::{
    build_fabric, CacheTransferAgent, NixlNodeId, NodeRegistry, RemoteBlock, TransferOutcome,
};
use crate::radix_cache::KvCacheHandle;

// ---------------------------------------------------------------------------
// Node role
// ---------------------------------------------------------------------------

/// Role assigned to a NIXL node inside a [`DisaggPool`].
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum NodeRole {
    /// Processes the prompt (compute-bound attention over full context).
    Prefill,
    /// Runs the auto-regressive decode loop (memory-bandwidth-bound).
    Decode,
}

impl std::fmt::Display for NodeRole {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            NodeRole::Prefill => write!(f, "prefill"),
            NodeRole::Decode => write!(f, "decode"),
        }
    }
}

// ---------------------------------------------------------------------------
// Task types
// ---------------------------------------------------------------------------

/// A prompt to be processed by a prefill node.
#[derive(Debug, Clone)]
pub struct PrefillTask {
    /// Unique request identifier (used for affinity tracking).
    pub request_id: u64,
    /// The prompt token sequence.
    pub tokens: Vec<u32>,
    /// Optional raw KV bytes generated by the prefill model.
    /// If `None`, a zero-payload block is transferred (valid for testing).
    pub kv_payload: Option<Vec<u8>>,
}

/// A decode task delivered to a decode node after KV migration.
#[derive(Debug, Clone)]
pub struct DecodeTask {
    pub request_id: u64,
    /// The KV-cache handle allocated by the prefill node.
    pub kv_handle: KvCacheHandle,
    /// The migrated KV block received from the prefill node via NIXL.
    pub remote_block: RemoteBlock,
    /// Which prefill node produced this block (for telemetry / affinity).
    pub prefill_origin: NixlNodeId,
}

// ---------------------------------------------------------------------------
// Disaggregated pool
// ---------------------------------------------------------------------------

/// Aggregated statistics across both pools.
#[derive(Debug, Clone, Default)]
pub struct DisaggStats {
    pub prefill_tasks_routed: u64,
    pub decode_tasks_dispatched: u64,
    pub kv_blocks_migrated: u64,
    pub kv_bytes_migrated: u64,
    pub migration_failures: u64,
}

/// Orchestrates prefill and decode node pools over the NIXL fabric.
///
/// # Usage
///
/// ```
/// use velo_core::disagg::{build_disagg_pool, PrefillTask};
///
/// let mut pool = build_disagg_pool(2, 2, 256, 4, 100_000);
/// let task = PrefillTask { request_id: 1, tokens: vec![1, 2, 3], kv_payload: None };
/// let decode_tasks = pool.run_prefill(task);
/// assert_eq!(decode_tasks.len(), 1);
/// ```
pub struct DisaggPool {
    /// NIXL agents assigned to the prefill role (one per physical node).
    prefill_agents: Vec<CacheTransferAgent>,
    /// NIXL agents assigned to the decode role (one per physical node).
    decode_agents: Vec<CacheTransferAgent>,
    /// Shared node registry (both pools are registered here).
    pub registry: Arc<NodeRegistry>,
    /// Round-robin cursor for prefill agent selection.
    prefill_cursor: usize,
    /// Round-robin cursor for decode agent selection.
    decode_cursor: usize,
    /// Aggregated telemetry.
    pub stats: DisaggStats,
}

impl std::fmt::Debug for DisaggPool {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("DisaggPool")
            .field("prefill_nodes", &self.prefill_agents.len())
            .field("decode_nodes", &self.decode_agents.len())
            .field("stats", &self.stats)
            .finish()
    }
}

impl DisaggPool {
    /// Route a prefill task through a prefill node, then migrate the resulting
    /// KV block to a decode node via NIXL.
    ///
    /// Returns the list of [`DecodeTask`]s ready for decode-side processing
    /// (one per successfully migrated block; empty on total migration failure).
    pub fn run_prefill(&mut self, task: PrefillTask) -> Vec<DecodeTask> {
        self.stats.prefill_tasks_routed += 1;

        // 1. Pick a prefill agent (round-robin).
        let prefill_idx = self.prefill_cursor % self.prefill_agents.len();
        self.prefill_cursor = self.prefill_cursor.wrapping_add(1);

        // 2. Build a synthetic KV handle for the prefill output.
        //    In production this comes from the model's KV-cache allocator.
        let token_len = task.tokens.len();
        let handle = KvCacheHandle {
            block_id: task.request_id,
            token_len,
        };
        let payload = task.kv_payload.clone().unwrap_or_default();

        // 3. Ship the block to a decode node via NIXL.
        let decode_node_ids = self.decode_node_ids();
        let outcomes = self.prefill_agents[prefill_idx].handoff(&[handle], &[payload], Some(&decode_node_ids));
        let prefill_node_id = self.prefill_agents[prefill_idx].node_id;

        let mut decode_tasks = Vec::new();
        for outcome in &outcomes {
            match outcome {
                TransferOutcome::Sent { bytes, .. } => {
                    self.stats.kv_blocks_migrated += 1;
                    self.stats.kv_bytes_migrated += *bytes as u64;
                }
                _ => {
                    self.stats.migration_failures += 1;
                }
            }
        }

        // 4. Drain decode inboxes and assemble DecodeTask list.
        for agent in &mut self.decode_agents {
            for block in agent.drain_inbox() {
                if block.handle.block_id == task.request_id {
                    decode_tasks.push(DecodeTask {
                        request_id: task.request_id,
                        kv_handle: block.handle,
                        remote_block: block,
                        prefill_origin: prefill_node_id,
                    });
                }
            }
        }

        decode_tasks
    }

    /// Dispatch a [`DecodeTask`] to the next decode node (round-robin).
    ///
    /// In production this would submit to the decode worker's GPU queue;
    /// here it records the dispatch for observability.
    pub fn dispatch_decode(&mut self, _task: &DecodeTask) -> NixlNodeId {
        self.stats.decode_tasks_dispatched += 1;
        let idx = self.decode_cursor % self.decode_agents.len();
        self.decode_cursor = self.decode_cursor.wrapping_add(1);
        self.decode_agents[idx].node_id
    }

    /// Full end-to-end pipeline: prefill → NIXL migration → decode dispatch.
    ///
    /// Returns the assigned decode node IDs for each successfully migrated block.
    pub fn run_pipeline(&mut self, task: PrefillTask) -> Vec<(DecodeTask, NixlNodeId)> {
        let decode_tasks = self.run_prefill(task);
        decode_tasks
            .into_iter()
            .map(|dt| {
                let node = self.dispatch_decode(&dt);
                (dt, node)
            })
            .collect()
    }

    pub fn prefill_node_count(&self) -> usize {
        self.prefill_agents.len()
    }

    pub fn decode_node_count(&self) -> usize {
        self.decode_agents.len()
    }

    /// Node IDs of all prefill agents.
    pub fn prefill_node_ids(&self) -> Vec<NixlNodeId> {
        self.prefill_agents.iter().map(|a| a.node_id).collect()
    }

    /// Node IDs of all decode agents.
    pub fn decode_node_ids(&self) -> Vec<NixlNodeId> {
        self.decode_agents.iter().map(|a| a.node_id).collect()
    }
}

// ---------------------------------------------------------------------------
// Builder
// ---------------------------------------------------------------------------

/// Build a [`DisaggPool`] with `prefill_count` prefill nodes and `decode_count`
/// decode nodes, all registered on a shared NIXL fabric.
///
/// * `block_bytes` — size of each DMA region (bytes per KV block).
/// * `dma_pool`    — pre-registered DMA regions per agent.
/// * `capacity`    — token capacity per node (used for peer selection).
pub fn build_disagg_pool(
    prefill_count: usize,
    decode_count: usize,
    block_bytes: usize,
    dma_pool: usize,
    capacity: usize,
) -> DisaggPool {
    assert!(prefill_count > 0, "need at least one prefill node");
    assert!(decode_count > 0, "need at least one decode node");

    let total = prefill_count + decode_count;
    let (registry, mut agents) = build_fabric(total, block_bytes, dma_pool, capacity);

    // First `prefill_count` agents → prefill; remainder → decode.
    let decode_agents: Vec<CacheTransferAgent> = agents.drain(prefill_count..).collect();
    let prefill_agents = agents;

    DisaggPool {
        prefill_agents,
        decode_agents,
        registry,
        prefill_cursor: 0,
        decode_cursor: 0,
        stats: DisaggStats::default(),
    }
}

